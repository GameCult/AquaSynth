#!/usr/bin/env node
// The effects shelf: every sound AquaSynth can render headless today, as one machine-readable list (shelf.json) and a
// human page (SHELF.md), plus a check that runs each entry's render command and measures what it wrote.
// NOTHING HERE HEARS ANYTHING. `listening` stays "unheard" until a person edits it; the check proves a render is
// finite and not silent, which says nothing about whether it sounds good.
// Usage (from the repo root):
//   node tools/aqua-feel/shelf.mjs build             regenerate tools/aqua-feel/shelf.json and the table block of SHELF.md
//   node tools/aqua-feel/shelf.mjs check [--only S]  run every entry's render command, read the WAVs back, fail on silence/NaN/drift
//   node tools/aqua-feel/shelf.mjs render ID [k=v ...] --out FILE.wav [--seconds N]   render one patch or ding (what the entries call)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { execSync } from "node:child_process";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { SR, SILENT_PEAK, samplePeak, measure } from "./metrics.js";
import { loadRuntime, compile, renderOnce, renderDing, writeWav, readText, playground } from "./render.js";
import { PATCH_SECONDS, DING_COMMAND_GAIN } from "./catalog.js";
import { EVENTS, IDENTITIES, DEFAULT_PARAMS, PARAM_RANGES, renderFamily, fileName } from "../earcon-workshop/web/earcon.js";

const here = dirname(fileURLToPath(import.meta.url)), root = resolve(here, "../..");
const SHELF_JSON = join(here, "shelf.json"), SHELF_MD = join(here, "SHELF.md");
const OUT = "tools/aqua-feel/out/shelf";                 // relative to the repo root, gitignored
const BEGIN = "<!-- shelf:begin (generated by `node tools/aqua-feel/shelf.mjs build`; do not edit) -->", END = "<!-- shelf:end -->";
const dingsDir = join(here, "lowered-dings");
const r3 = (x) => Math.round(x * 1000) / 1000;

const args = process.argv.slice(2), cmd = args.shift();
const flag = (n) => { const i = args.indexOf(n); if (i < 0) return undefined; return args.splice(i, 2)[1]; };

function controlsOf(entry) {   // Faust UI -> shelf params; the ranges are the DSP's own declarations
  const out = [];
  const walk = (items) => { for (const it of items ?? []) {
    if (it.items) walk(it.items);
    else if (it.address) {
      const name = it.label.replace(/^\//, "");
      if (/slider|nentry/i.test(it.type)) out.push({ name, kind: "slider", min: Number(it.min), max: Number(it.max), default: Number(it.init), step: Number(it.step) });
      else out.push({ name, kind: it.type });            // button / checkbox: reported as declared, not interpreted
    } } };
  walk(JSON.parse(entry.g.factory.json).ui);
  return out;
}

async function build() {
  const rt = await loadRuntime(), entries = [];
  const dir = join(playground, "lowered"), cat = JSON.parse(readText(join(dir, "catalog.json")));
  for (const e of cat) {
    const entry = await compile(rt, e.name, readText(join(dir, e.dsp)));
    const params = controlsOf(entry), r = await renderOnce(entry, {}, PATCH_SECONDS), x = r.samples, tail = x.slice(x.length - Math.round(SR * 0.2));
    const m = measure(x), sustained = samplePeak(tail) >= 0.1 * samplePeak(x);
    const isThruster = e.name === "thruster";
    entries.push({
      id: `patch/${e.name}`, group: isThruster ? "thruster" : "patch", name: e.name, family: e.name.split("-")[0],
      source: e.kind === "faust" ? `tools/aqua-playground/lowered/${e.dsp}` : `tools/aqua-playground/lowered/${e.dsp} (lowered from patches/${e.origin})`,
      params,
      reacts_to: isThruster
        ? { kind: "control", detail: "the rpm slider (300..6000, smoothed over 0.2 s): drive it from whatever number should make the thruster work harder. Nothing in the repo maps a stream metric to rpm." }
        : { kind: "start", detail: "plays from the moment it is started; no gate, trigger or audio-feature input. Sliders, where listed, are live while it plays." },
      behaviour: sustained ? "sustained: still sounding at the end of the render window, runs until stopped" : "decays: dies away inside the render window",
      duration_s: PATCH_SECONDS, duration_note: "the render window, not the effect's length",
      render: { command: `node tools/aqua-feel/shelf.mjs render patch/${e.name} --out ${OUT}/patch_${e.name}.wav`, outputs: [{ file: `${OUT}/patch_${e.name}.wav`, duration_s: PATCH_SECONDS }] },
      ...(isThruster ? { check_variants: [300, 6000].map((rpm) => ({ params: { rpm }, command: `node tools/aqua-feel/shelf.mjs render patch/${e.name} rpm=${rpm} --out ${OUT}/patch_${e.name}_rpm${rpm}.wav`, outputs: [{ file: `${OUT}/patch_${e.name}_rpm${rpm}.wav`, duration_s: PATCH_SECONDS }] })) } : {}),
      listening: "unheard",
    });
  }
  const d = JSON.parse(readText(join(dingsDir, "dings.json"))), instruments = d.instruments.map((i) => i.id), DEF_INS = "warm-bell";
  for (const ev of d.events) {
    const dur = r3(d.noteSeconds + Math.max(...ev.notes.map((n) => n.delayMilliseconds)) / 1000);
    const one = (ins) => ({ command: `node tools/aqua-feel/shelf.mjs render ding/${ev.id} instrument=${ins} --out ${OUT}/ding_${ev.id}_${ins}.wav`, outputs: [{ file: `${OUT}/ding_${ev.id}_${ins}.wav`, duration_s: dur }] });
    entries.push({
      id: `ding/${ev.id}`, group: "ding", name: ev.id, family: "dings",
      source: "tools/aqua-feel/lowered-dings (lowered from src DingCatalog)",
      params: [{ name: "instrument", kind: "enum", values: instruments, default: DEF_INS, note: `no instrument is the shipped default in the catalog; ${DEF_INS} is the shelf's choice` }],
      reacts_to: { kind: "event", event_id: ev.id, detail: `Ding event "${ev.id}": ${ev.meaning}. A Ding event is ${ev.notes.length} note(s) at semitones ${ev.notes.map((n) => n.semitones).join(", ")} above ${d.instruments[0].rootFrequency} Hz. Mapping stream events onto Ding events is not done anywhere.` },
      behaviour: "decays",
      duration_s: dur, duration_note: `${d.noteSeconds} s per note plus the last note's delay; command gain ${DING_COMMAND_GAIN} is an assumption (aqua-feel README)`,
      render: one(DEF_INS),
      check_variants: instruments.filter((i) => i !== DEF_INS).map((i) => ({ params: { instrument: i }, ...one(i) })),
      listening: "unheard",
    });
  }
  for (const [id, ident] of Object.entries(IDENTITIES)) {
    const fam = renderFamily(id), outDir = `${OUT}/earcon/${id}`;
    entries.push({
      id: `earcon/${id}`, group: "earcon", name: id, family: "earcon-workshop",
      source: "tools/earcon-workshop/web/earcon.js (plain JS reimplementation; not the Dings .aqua scripts, so it does not sound like the Dings)",
      params: Object.entries(PARAM_RANGES).map(([name, [min, max, step]]) => ({ name, kind: "slider", min, max, step, default: DEFAULT_PARAMS[name] })),
      reacts_to: { kind: "event", events: Object.entries(EVENTS).map(([k, v]) => ({ event_id: k, detail: v.meaning })), detail: "one WAV per event; the caller picks the file for the event it has. Voice: " + ident.note },
      behaviour: "decays",
      duration_s: r3(Math.max(...fam.items.map((i) => i.durationMs)) / 1000), duration_note: "longest of the six event WAVs at default sliders",
      render: { command: `node tools/earcon-workshop/cli.mjs ${id} ${outDir}`, outputs: fam.items.map((i) => ({ file: `${outDir}/${fileName(id, i.event)}`, duration_s: r3(i.durationMs / 1000) })) },
      listening: "unheard",
    });
  }
  return { schema: "aquasynth.effects-shelf.v0", note: "Generated by tools/aqua-feel/shelf.mjs build. Nothing here was heard: every entry's listening status is 'unheard'. Commands run from the repo root.", sampleRate: SR, entries };
}

function tableBlock(shelf) {
  const rng = (p) => p.kind === "slider" ? `${p.name} ${p.min}..${p.max} (default ${p.default})` : p.kind === "enum" ? `${p.name} ∈ {${p.values.join(", ")}} (default ${p.default})` : `${p.name} (${p.kind})`;
  const L = [BEGIN, ""];
  for (const [title, pick] of [["Thruster", (e) => e.group === "thruster"], ["Dings (event sounds)", (e) => e.group === "ding"], ["Earcon workshop (one WAV per event)", (e) => e.group === "earcon"], ["Playground patches (one-shot and sustained synth sounds)", (e) => e.group === "patch"]]) {
    const es = shelf.entries.filter(pick);
    L.push(`### ${title} (${es.length})`, "", "| id | reacts to | params | behaviour | duration | listening |", "|---|---|---|---|---|---|");
    for (const e of es) {
      const re = e.reacts_to.kind === "event" && e.reacts_to.events ? `events: ${e.reacts_to.events.map((v) => v.event_id).join(", ")}` : e.reacts_to.kind === "event" ? `event \`${e.reacts_to.event_id}\`` : e.reacts_to.kind === "control" ? "control: rpm" : "start";
      L.push(`| \`${e.id}\` | ${re} | ${e.params.map(rng).join("; ") || "none"} | ${e.behaviour.split(":")[0]} | ${e.duration_s} s | ${e.listening} |`);
    }
    L.push("");
  }
  L.push(END);
  return L.join("\n");
}

function writeShelf(shelf) {
  writeFileSync(SHELF_JSON, JSON.stringify(shelf, null, 1) + "\n");
  const md = readFileSync(SHELF_MD, "utf8"), a = md.indexOf(BEGIN), b = md.indexOf(END);
  if (a < 0 || b < 0) throw new Error("SHELF.md has no generated block markers");
  writeFileSync(SHELF_MD, md.slice(0, a) + tableBlock(shelf) + md.slice(b + END.length));
}

// ---- render: what the entries' commands call ------------------------------------------------------------------------
async function render() {
  const out = flag("--out"), seconds = flag("--seconds"), [id, ...kv] = args;
  if (!id || !out) { console.error("usage: shelf.mjs render ID [k=v ...] --out FILE.wav [--seconds N]"); process.exit(2); }
  const params = Object.fromEntries(kv.map((s) => s.split("=")).map(([k, v]) => [k, isNaN(Number(v)) ? v : Number(v)]));
  const rt = await loadRuntime(); let samples;
  if (id.startsWith("patch/")) {
    const name = id.slice(6), dir = join(playground, "lowered"), e = JSON.parse(readText(join(dir, "catalog.json"))).find((x) => x.name === name);
    if (!e) { console.error(`no patch ${name}`); process.exit(2); }
    samples = (await renderOnce(await compile(rt, name, readText(join(dir, e.dsp))), params, seconds ? Number(seconds) : PATCH_SECONDS)).samples;
  } else if (id.startsWith("ding/")) {
    const d = JSON.parse(readText(join(dingsDir, "dings.json"))), ev = d.events.find((x) => x.id === id.slice(5)), ins = d.instruments.find((x) => x.id === (params.instrument ?? "warm-bell"));
    if (!ev || !ins) { console.error(`no ding event ${id.slice(5)} / instrument ${params.instrument}`); process.exit(2); }
    samples = (await renderDing(rt, ins, readText(join(dingsDir, ins.dsp)), ev, { noteSeconds: d.noteSeconds, commandGain: DING_COMMAND_GAIN })).samples;
  } else { console.error("render handles patch/ and ding/ ids; earcon entries use tools/earcon-workshop/cli.mjs"); process.exit(2); }
  writeWav(resolve(out), samples);
  console.log(`wrote ${out} (${(samples.length / SR).toFixed(3)} s)`);
}

// ---- check -----------------------------------------------------------------------------------------------------------
function readWav(path) {   // PCM16 or float32 mono, as this repo's two writers produce
  const b = readFileSync(path), v = new DataView(b.buffer, b.byteOffset, b.byteLength);
  if (b.toString("latin1", 0, 4) !== "RIFF" || b.toString("latin1", 8, 12) !== "WAVE") throw new Error("not a RIFF/WAVE file");
  const tag = v.getUint16(20, true), ch = v.getUint16(22, true), sr = v.getUint32(24, true), bits = v.getUint16(34, true), n = v.getUint32(40, true) / (bits / 8);
  if (ch !== 1 || !((tag === 1 && bits === 16) || (tag === 3 && bits === 32))) throw new Error(`unsupported wav tag ${tag} bits ${bits} channels ${ch}`);
  const x = new Float32Array(n);
  for (let i = 0; i < n; i++) x[i] = tag === 3 ? v.getFloat32(44 + i * 4, true) : v.getInt16(44 + i * 2, true) / 32768;
  return { sr, x };
}

async function check() {
  const only = flag("--only"), problems = [], rows = [];
  mkdirSync(join(root, OUT), { recursive: true });
  const fresh = await build(), onDisk = existsSync(SHELF_JSON) ? readFileSync(SHELF_JSON, "utf8") : "";
  if (onDisk !== JSON.stringify(fresh, null, 1) + "\n") problems.push("shelf.json is stale: run `node tools/aqua-feel/shelf.mjs build`");
  const md = readFileSync(SHELF_MD, "utf8"), a = md.indexOf(BEGIN), b = md.indexOf(END);
  if (a < 0 || md.slice(a, b + END.length) !== tableBlock(fresh)) problems.push("SHELF.md table block is stale: run `node tools/aqua-feel/shelf.mjs build`");
  for (const e of fresh.entries.filter((x) => !only || x.id.includes(only))) {
    if (e.listening !== "unheard") problems.push(`${e.id}: listening is '${e.listening}'; this check cannot confirm that`);
    for (const r of [e.render, ...(e.check_variants ?? [])]) {
      try {
        execSync(r.command, { cwd: root, stdio: ["ignore", "pipe", "pipe"] });
        for (const o of r.outputs) {
          const { sr, x } = readWav(join(root, o.file)), peak = samplePeak(x), dur = x.length / sr;
          if (sr !== SR) throw new Error(`${o.file}: sample rate ${sr}`);
          if (!x.every(Number.isFinite)) throw new Error(`${o.file}: non-finite samples`);
          if (peak < SILENT_PEAK) throw new Error(`${o.file}: silent (peak ${peak}, floor ${SILENT_PEAK.toFixed(6)})`);
          if (Math.abs(dur - o.duration_s) > 0.01) throw new Error(`${o.file}: ${dur.toFixed(3)} s, shelf says ${o.duration_s} s`);
          rows.push(`ok   ${o.file.replace(OUT + "/", "")}  peak ${(20 * Math.log10(peak)).toFixed(1)} dBFS  ${dur.toFixed(3)} s  [${r.command}]`);
        }
      } catch (err) { problems.push(`${e.id}: ${r.command}\n     ${String(err.message ?? err).split("\n")[0]}`); }
    }
  }
  console.log(rows.join("\n"));
  console.log(`\n${rows.length} rendered file(s) checked across ${fresh.entries.filter((x) => !only || x.id.includes(only)).length} entries. Nothing here was heard.`);
  if (problems.length) { console.log(`\nFAIL (${problems.length}):\n` + problems.map((p) => "  " + p).join("\n")); process.exit(1); }
  console.log("PASS: every render command ran, every WAV is finite, not silent, and as long as the shelf says; shelf.json and SHELF.md are current.");
}

const cmds = { build: async () => { const s = await build(); writeShelf(s); console.log(`wrote ${SHELF_JSON}: ${s.entries.length} entries`); }, render, check };
if (!cmds[cmd]) { console.error(readFileSync(fileURLToPath(import.meta.url), "utf8").split("\n").slice(1, 9).join("\n")); process.exit(2); }
await cmds[cmd]();
